def main() -> None:
    """Generate all missing locale files."""
    created = 0
    for locale_code, data in LOCALES.items():
        path = LOCALES_DIR / f"{locale_code}.json"
        if path.exists():
            print(f"  SKIP {locale_code} (already exists)")
            continue

        with open(path, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=4)

        n_trans = len(data.get("translations", {}))
        n_plurals = len(data.get("plural_translations", {}))
        print(f"  CREATE {locale_code}: {n_trans} translations, {n_plurals} plural keys")
        created += 1

    print(f"\nDone: created {created} locale files out of {len(LOCALES)} requested.")


if __name__ == "__main__":
    main()
