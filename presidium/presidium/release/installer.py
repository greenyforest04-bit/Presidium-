"""Installer builder for Presidium.

Generates platform-specific installers using PyInstaller for
bundling the application into standalone executables.

Supported platforms:
    - Windows: .exe installer
    - macOS: .app bundle + .dmg
    - Linux: .AppImage + .deb

Usage:
    builder = InstallerBuilder()
    await builder.build(platform="linux")
"""

from __future__ import annotations

import asyncio
import logging
import os
import platform
import shutil
import subprocess
import sys
from pathlib import Path
from typing import Optional

logger = logging.getLogger(__name__)


# ---------------------------------------------------------------------------
# PyInstaller spec content
# ---------------------------------------------------------------------------

PYINSTALLER_SPEC = """# -*- mode: python ; coding: utf-8 -*-
# Presidium PyInstaller spec file
# Auto-generated by InstallerBuilder

import sys
from PyInstaller.utils.hooks import collect_data_files, collect_submodules

block_cipher = None

# Collect all presidium submodules
hidden_imports = collect_submodules('presidium')
hidden_imports += [
    'aiosqlite',
    'argon2',
    'aiortc',
    'msgspec',
    'pydantic',
    'pydantic_settings',
    'qasync',
    'aiohttp',
    'psutil',
]

# Collect data files (themes, icons)
datas = []
datas += collect_data_files('PySide6')

a = Analysis(
    ['presidium/main.py'],
    pathex=[],
    binaries=[],
    datas=datas,
    hiddenimports=hidden_imports,
    hookspath=[],
    hooksconfig={{}},
    runtime_hooks=[],
    excludes=[
        'tkinter',
        'matplotlib',
        'numpy',
        'scipy',
        'PIL',
        'pytest',
    ],
    win_no_prefer_redirects=False,
    win_private_assemblies=False,
    cipher=block_cipher,
    noarchive=False,
)

pyz = PYZ(a.pure, a.zipped_data, cipher=block_cipher)

exe = EXE(
    pyz,
    a.scripts,
    [],
    exclude_binaries=True,
    name='presidium',
    debug=False,
    bootloader_ignore_signals=False,
    strip=False,
    upx=True,
    console=False,
    disable_windowed_traceback=False,
    argv_emulation=False,
    target_arch=None,
    codesign_identity=None,
    entitlements_file=None,
    icon='presidium/ui/assets/icon.ico' if sys.platform == 'win32' else None,
)

coll = COLLECT(
    exe,
    a.binaries,
    a.zipfiles,
    a.datas,
    strip=False,
    upx=True,
    upx_exclude=[],
    name='presidium',
)

# macOS app bundle
if sys.platform == 'darwin':
    app = BUNDLE(
        coll,
        name='Presidium.app',
        icon='presidium/ui/assets/icon.icns',
        bundle_identifier='chat.presidium.app',
        info_plist={{
            'CFBundleShortVersionString': '0.4.0',
            'CFBundleName': 'Presidium',
            'NSHighResolutionCapable': True,
            'LSMinimumSystemVersion': '11.0',
        }},
    )
"""


# ---------------------------------------------------------------------------
# Installer builder
# ---------------------------------------------------------------------------

class InstallerBuilder:
    """Builds platform-specific installers for Presidium.

    Uses PyInstaller to create standalone executables and then
    wraps them in platform-specific installer formats.
    """

    def __init__(
        self,
        source_dir: Optional[Path] = None,
        output_dir: Optional[Path] = None,
    ) -> None:
        self._source_dir = source_dir or Path(__file__).parent.parent.parent
        self._output_dir = output_dir or self._source_dir / "dist"

    async def build(
        self,
        target_platform: Optional[str] = None,
        clean: bool = True,
        onefile: bool = False,
    ) -> Path:
        """Build the installer for the specified platform.

        Args:
            target_platform: Target platform (linux, darwin, win32).
                Defaults to current platform.
            clean: Whether to clean previous build artifacts.
            onefile: Build as a single executable (larger, slower startup).

        Returns:
            Path to the output directory containing the installer.
        """
        if target_platform is None:
            target_platform = sys.platform

        logger.info(
            "Building Presidium installer for %s (onefile=%s)",
            target_platform, onefile,
        )

        # Clean previous builds
        if clean:
            build_dir = self._source_dir / "build"
            if build_dir.exists():
                shutil.rmtree(build_dir)
            if self._output_dir.exists():
                shutil.rmtree(self._output_dir)

        # Generate spec file
        spec_path = self._source_dir / "presidium.spec"
        with open(spec_path, "w", encoding="utf-8") as f:
            f.write(PYINSTALLER_SPEC)

        # Build PyInstaller command
        cmd = [
            sys.executable, "-m", "PyInstaller",
            "--clean",
            "--noconfirm",
            "--name", "presidium",
            "--windowed",  # No console window
        ]

        if onefile:
            cmd.append("--onefile")

        # Platform-specific options
        if target_platform == "darwin":
            cmd.extend(["--osx-bundle-identifier", "chat.presidium.app"])

        # Add data files
        cmd.extend([
            "--add-data", f"presidium/ui/styles{os.pathsep}presidium/ui/styles",
        ])

        # Hidden imports
        hidden_imports = [
            "aiosqlite", "argon2", "aiortc", "msgspec",
            "pydantic", "pydantic_settings", "qasync", "aiohttp",
        ]
        for imp in hidden_imports:
            cmd.extend(["--hidden-import", imp])

        cmd.append(str(self._source_dir / "presidium" / "main.py"))

        # Run PyInstaller
        try:
            process = await asyncio.create_subprocess_exec(
                *cmd,
                cwd=str(self._source_dir),
                stdout=asyncio.subprocess.PIPE,
                stderr=asyncio.subprocess.PIPE,
            )
            stdout, stderr = await process.communicate()

            if process.returncode != 0:
                logger.error("PyInstaller failed:\n%s", stderr.decode())
                raise InstallerBuildError(
                    f"PyInstaller exited with code {process.returncode}"
                )

            logger.info("Build complete. Output at %s", self._output_dir)
            return self._output_dir

        except FileNotFoundError:
            raise InstallerBuildError(
                "PyInstaller not found. Install with: pip install pyinstaller"
            )

    async def build_appimage(self) -> Path:
        """Build a Linux AppImage.

        Only available on Linux. Creates a portable AppImage that
        runs on any Linux distribution without installation.
        """
        if sys.platform != "linux":
            raise InstallerBuildError("AppImage build only supported on Linux.")

        # First build the regular PyInstaller output
        dist_dir = await self.build(target_platform="linux")

        # Create AppDir structure
        appdir = self._output_dir / "Presidium.AppDir"
        appdir.mkdir(parents=True, exist_ok=True)

        # Copy PyInstaller output
        usr_dir = appdir / "usr"
        if usr_dir.exists():
            shutil.rmtree(usr_dir)
        shutil.copytree(str(dist_dir / "presidium"), str(usr_dir))

        # Create desktop entry
        desktop = appdir / "presidium.desktop"
        desktop.write_text("""[Desktop Entry]
Name=Presidium
Exec=usr/presidium
Icon=presidium
Type=Application
Categories=Network;Chat;Security;
Comment=Decentralized E2EE P2P Messenger
""")

        # Download appimagetool (simplified)
        logger.info("AppImage structure created at %s", appdir)
        return appdir


# ---------------------------------------------------------------------------
# Exceptions
# ---------------------------------------------------------------------------

class InstallerBuildError(Exception):
    """Error during installer build."""
